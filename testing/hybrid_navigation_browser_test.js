const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
function element() {
    return {attrs:{},events:{},focused:false,setAttribute(key,value){this.attrs[key]=value;},
        addEventListener(key,callback){this.events[key]=callback;},focus(){this.focused=true;}};
}
const button=element(), toggle={checked:true}, drawer=element(), scrim=element(), first=element();
drawer.querySelector=selector=>selector === '.hybrid-drawer-close' ? null : first;
drawer.querySelectorAll=()=>[first];
const media={matches:false,addEventListener(key,callback){this.change=callback;}};
const document=element();
document.getElementById=id=>({'hybrid-menu-button':button,'hybrid-menu-toggle':toggle,'hybrid-navigation':drawer}[id]);
document.querySelector=()=>scrim;
document.querySelectorAll=()=>[];
document.body={classList:{toggle(){}}};
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'../indi_allsky/flask/static/modern_admin/navigation.js'),'utf8'),{document,window:{matchMedia:()=>media}});
assert.equal(toggle.checked,false);
assert.equal(drawer.inert,true);
button.events.click();
assert.equal(toggle.checked,true);
assert.equal(drawer.inert,false);
assert.equal(button.attrs['aria-expanded'],'true');
assert.equal(first.focused,true);
let prevented=false;
document.events.keydown({key:'Escape',preventDefault(){prevented=true;}});
assert.equal(prevented,true);
assert.equal(toggle.checked,false);
assert.equal(button.focused,true);
button.events.click();
drawer.events.click({target:{closest:()=>({})}});
assert.equal(toggle.checked,false);
button.events.click();
drawer.events.click({target:{closest:()=>null}});
assert.equal(toggle.checked,true);
scrim.events.click();
assert.equal(toggle.checked,false);
media.matches=true;
media.change();
assert.equal(drawer.inert,false);
assert.equal(drawer.attrs['aria-hidden'],'false');
button.events.click();
assert.equal(toggle.checked,false);
media.matches=false;
media.change();
assert.equal(drawer.inert,true);
console.log('Hybrid navigation controller: mobile drawer and persistent desktop navigation PASS');
